create or replace function notifyPurchaseOrder(poid uuid, op text)
returns void
language plpgsql
as $$
declare
  data json;
begin
  if op <> 'delete' then
    data := purchaseOrderRow(poid);

    -- A line deleted by the cascade of its order's delete finds no order.
    if data is null then
      return;
    end if;
  end if;

  perform liveNotify('purchase_orders', op, poid, data);
end;
$$;

create or replace function purchaseOrdersNotify()
returns trigger
language plpgsql
as $$
declare
  r record;
begin
  r := coalesce(new, old);
  perform notifyPurchaseOrder(r.id, lower(tg_op));

  return r;
end;
$$;

create trigger purchaseOrdersNotifyTrigger
  after insert or update or delete on purchaseOrders
  for each row execute function purchaseOrdersNotify();

create or replace function poLinesNotify()
returns trigger
language plpgsql
as $$
declare
  r record;
  op text := lower(tg_op);
  data json;
begin
  r := coalesce(new, old);

  if op <> 'delete' then
    data := poLineRow(r.id);
  end if;

  perform liveNotify('po_lines', op, r.id, data);

  -- The order's totals move with its lines.
  perform notifyPurchaseOrder(r.purchaseOrderId, 'update');

  return r;
end;
$$;

create trigger poLinesNotifyTrigger
  after insert or update or delete on poLines
  for each row execute function poLinesNotify();
